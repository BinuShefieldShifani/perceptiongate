"""Run the pipeline as a Kaggle job from CI. Standard library only.

    python scripts/kaggle_job.py pick-config --base origin/main
    python scripts/kaggle_job.py build --config configs/experiments/x.yaml --sha <commit> --out job/
    python scripts/kaggle_job.py wait --kernel <user>/perceptiongate-run --timeout-min 170
    python scripts/kaggle_job.py summary --outputs out/ --name x

`build` writes a Kaggle "script" kernel: kernel-metadata.json (GPU + internet + the prepared
dataset) and run.py, which clones this repo at the exact commit and runs the full pipeline.
Everything a PR comment needs ends up in /kaggle/working/result/.
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
import time
from pathlib import Path

REPO_URL = "https://github.com/BinuShefieldShifani/perceptiongate.git"
DATASET = "binushifani/perceptiongate-bdd100k-v1-640"
KERNEL_SLUG = "perceptiongate-run"
AGENT_MODEL = "qwen2.5:14b"
MARKER = "<!-- perceptiongate-comment -->"

RUN_PY = '''"""Generated by scripts/kaggle_job.py. Do not edit by hand."""
import glob, os, shutil, subprocess, sys

SHA = {sha!r}
CONFIG = {config!r}
AGENT_MODEL = {agent_model!r}
REPO_URL = {repo_url!r}

def sh(*cmd, check=True):
    print("+", " ".join(cmd), flush=True)
    return subprocess.run(list(cmd), check=check)

os.chdir("/kaggle/working")
sh("git", "clone", "-q", REPO_URL, "repo")
os.chdir("repo")
sh("git", "checkout", "-q", SHA)
sh(sys.executable, "-m", "pip", "install", "-q", "-e", ".[train,tracking]")

bins = glob.glob("/kaggle/input/**/*.bin", recursive=True)
if len(bins) != 1:
    sys.exit(f"expected one prepared dataset .bin, found {{bins}}")
shutil.copy(bins[0], "/kaggle/working/data.tar")

name = os.path.splitext(os.path.basename(CONFIG))[0]
sh(sys.executable, "scripts/kaggle_train.py", "--config", CONFIG,
   "--prepared", "/kaggle/working/data.tar", "--agent-model", AGENT_MODEL)

# Keep the job output small: only what CI and people need.
result = "/kaggle/working/result"
os.makedirs(result, exist_ok=True)
out = f"/kaggle/working/outputs/{{name}}"
for f in ("metrics.json", "run_info.json", "tracking.json"):
    if os.path.exists(f"{{out}}/{{f}}"):
        shutil.copy(f"{{out}}/{{f}}", result)
if os.path.isdir(f"{{out}}/eval"):
    shutil.copytree(f"{{out}}/eval", f"{{result}}/eval")
if os.path.exists(f"{{out}}/model/best.pt"):
    shutil.copy(f"{{out}}/model/best.pt", result)
os.chdir("/kaggle/working")
for junk in ("yolo", "outputs", "repo"):
    shutil.rmtree(junk, ignore_errors=True)
if os.path.exists("data.tar"):
    os.remove("data.tar")
print("RESULT_READY", flush=True)
'''


def pick_config(base: str) -> str:
    """The single experiment config changed in this PR."""
    out = subprocess.run(
        ["git", "diff", "--name-only", "--diff-filter=AM", f"{base}...HEAD"],
        capture_output=True, text=True, check=True,
    ).stdout  # fmt: skip
    return choose_config(out.splitlines())


def choose_config(changed: list[str]) -> str:
    configs = [p for p in changed if re.fullmatch(r"configs/experiments/[\w.-]+\.ya?ml", p)]
    configs = [p for p in configs if not p.endswith("smoke.yaml")]
    if len(configs) != 1:
        raise SystemExit(
            f"A 'train' PR must change exactly one experiment config; found {len(configs)}: "
            f"{configs}. Put the experiment in its own config file."
        )
    return configs[0]


def build(config: str, sha: str, user: str, out: Path, agent_model: str = AGENT_MODEL) -> Path:
    if not re.fullmatch(r"[0-9a-f]{7,40}", sha):
        raise SystemExit(f"not a commit sha: {sha!r}")
    out.mkdir(parents=True, exist_ok=True)
    (out / "run.py").write_text(
        RUN_PY.format(sha=sha, config=config, agent_model=agent_model, repo_url=REPO_URL)
    )
    meta = {
        "id": f"{user}/{KERNEL_SLUG}",
        "title": KERNEL_SLUG,
        "code_file": "run.py",
        "language": "python",
        "kernel_type": "script",
        "is_private": True,
        "enable_gpu": True,
        "enable_internet": True,
        "dataset_sources": [DATASET],
        "competition_sources": [],
        "kernel_sources": [],
    }
    (out / "kernel-metadata.json").write_text(json.dumps(meta, indent=2) + "\n")
    return out


def parse_status(text: str) -> str:
    """Map `kaggle kernels status` output to running / complete / error."""
    t = text.lower()
    if "complete" in t:
        return "complete"
    if any(w in t for w in ("error", "cancel", "fail")):
        return "error"
    return "running"


def wait(kernel: str, timeout_min: float, poll_s: float = 60) -> str:
    deadline = time.monotonic() + timeout_min * 60
    while time.monotonic() < deadline:
        res = subprocess.run(
            ["kaggle", "kernels", "status", kernel], capture_output=True, text=True
        )
        status = parse_status(res.stdout + res.stderr)
        print(f"[{time.strftime('%H:%M:%S')}] {status}: {res.stdout.strip()}", flush=True)
        if status != "running":
            return status
        time.sleep(poll_s)
    return "timeout"


def summary(outputs: Path, name: str) -> dict[str, object]:
    """Comment body and gate decision from downloaded job outputs."""
    comment = next(iter(sorted(outputs.rglob("pr_comment.md"))), None)
    gate = next(iter(sorted(outputs.rglob("gate_result.json"))), None)
    decision = json.loads(gate.read_text())["decision"] if gate else "ERROR"
    if comment:
        body = comment.read_text()
    else:
        body = (
            f"## PerceptionGate: ⚠️ no result · `{name}`\n\nThe Kaggle job finished without "
            "producing a comment. See the job log in the workflow artifacts."
        )
    return {"decision": decision, "body": f"{MARKER}\n{body}"}


def main() -> int:
    p = argparse.ArgumentParser()
    sub = p.add_subparsers(dest="cmd", required=True)
    a = sub.add_parser("pick-config")
    a.add_argument("--base", default="origin/main")
    b = sub.add_parser("build")
    b.add_argument("--config", required=True)
    b.add_argument("--sha", required=True)
    b.add_argument("--user", required=True)
    b.add_argument("--out", type=Path, default=Path("kaggle-job"))
    b.add_argument("--agent-model", default=AGENT_MODEL)
    w = sub.add_parser("wait")
    w.add_argument("--kernel", required=True)
    w.add_argument("--timeout-min", type=float, default=170)
    w.add_argument("--poll-s", type=float, default=60)
    s = sub.add_parser("summary")
    s.add_argument("--outputs", type=Path, required=True)
    s.add_argument("--name", required=True)
    s.add_argument("--out", type=Path, default=Path("comment.json"))
    args = p.parse_args()

    if args.cmd == "pick-config":
        print(pick_config(args.base))
    elif args.cmd == "build":
        print(build(args.config, args.sha, args.user, args.out, args.agent_model))
    elif args.cmd == "wait":
        status = wait(args.kernel, args.timeout_min, args.poll_s)
        print(f"final status: {status}")
        return 0 if status == "complete" else 1
    elif args.cmd == "summary":
        result = summary(args.outputs, args.name)
        args.out.write_text(json.dumps(result))
        print(f"decision: {result['decision']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
